#!/usr/bin/env python3
"""Generates the libcuda.so.1 front for libc2ccuda.

We export every symbol the real driver exports. The ones implemented in
libc2ccuda.cpp (C2CAPI) come from the C++ side. Everything else gets a small
aarch64 trampoline that asks c2c_route() where to go: normally the real
driver, but if the thread's current context is a remote one and the call
isn't on the safe list it hits a stub returning CUDA_ERROR_NOT_SUPPORTED.
Better an error than quietly running on the wrong GPU.

usage: gen_tramp.py SYMS_TXT SOURCE.cpp OUT_DIR
"""
import re
import sys

syms_file, src_file, out = sys.argv[1:4]
names = sorted({l.strip() for l in open(syms_file) if l.strip().startswith('cu')})
src = open(src_file).read()
impl = set(re.findall(r'^C2CAPI\s+CUresult\s+(cu\w+)\s*\(', src, re.M))
impl |= set(re.findall(r'^MEMSET\w*\((cu\w+),', src, re.M))
missing = impl - set(names)
if missing:
    sys.exit(f'implemented but not exported by the driver: {sorted(missing)}')

# these are fine to run on the local shadow ctx (it's the same GPU model):
# ctx stack stuff, queries, host memory, JIT linker
SAFE = ('cuCtxGet', 'cuCtxSetCurrent', 'cuCtxPushCurrent', 'cuCtxPopCurrent',
        'cuFuncGet', 'cuOccupancy', 'cuStreamGetPriority', 'cuStreamGetFlags',
        'cuStreamGetCtx', 'cuStreamIsCapturing', 'cuStreamGetCaptureInfo',
        'cuGetError', 'cuDriverGetVersion', 'cuMemAllocHost', 'cuMemHostAlloc',
        'cuMemFreeHost', 'cuMemHostRegister', 'cuMemHostUnregister', 'cuMemHostGetFlags',
        'cuLink', 'cuProfiler', 'cuDeviceGet', 'cuDeviceCanAccessPeer', 'cuDeviceTotalMem',
        'cuDeviceComputeCapability', 'cuDevicePrimaryCtx', 'cuInit', 'cuModuleGetFunction',
        'cuFlushGPUDirectRDMAWrites', 'cuThreadExchangeStreamCaptureMode',
        'cuMemAddress', 'cuMemGetAllocationGranularity')

with open(f'{out}/tramp.S', 'w') as f:
    f.write('// generated by gen_tramp.py - do not edit\n.text\n')
    for i, n in enumerate(names):
        if n in impl:
            continue
        f.write(f'''.global {n}
.type {n}, %function
{n}:
  stp x29, x30, [sp, -224]!
  mov x29, sp
  stp x0, x1, [sp, 16]
  stp x2, x3, [sp, 32]
  stp x4, x5, [sp, 48]
  stp x6, x7, [sp, 64]
  str x8, [sp, 80]
  stp q0, q1, [sp, 96]
  stp q2, q3, [sp, 128]
  stp q4, q5, [sp, 160]
  stp q6, q7, [sp, 192]
  mov x0, {i}
  bl c2c_route
  mov x16, x0
  ldp q6, q7, [sp, 192]
  ldp q4, q5, [sp, 160]
  ldp q2, q3, [sp, 128]
  ldp q0, q1, [sp, 96]
  ldr x8, [sp, 80]
  ldp x6, x7, [sp, 64]
  ldp x4, x5, [sp, 48]
  ldp x2, x3, [sp, 32]
  ldp x0, x1, [sp, 16]
  ldp x29, x30, [sp], 224
  br x16
.size {n}, .-{n}
''')
    f.write('.section .data.rel.ro\n.global c2c_tramp_table\n.balign 8\nc2c_tramp_table:\n')
    for n in names:
        f.write(f'  .quad {n}\n')
    f.write('.section .note.GNU-stack,"",%progbits\n')

with open(f'{out}/tramp_names.inc', 'w') as f:
    f.write('// generated by gen_tramp.py - do not edit\n')
    f.write(f'static const unsigned kNumSyms = {len(names)};\n')
    f.write('static const char* const kSymNames[] = {\n' + ''.join(f'    "{n}",\n' for n in names) + '};\n')
    f.write('static const bool kSymSafe[] = {\n' +
            ''.join(f'    {"true" if n.startswith(SAFE) else "false"},\n' for n in names) + '};\n')
print(f'{len(names)} driver functions: {len(impl)} implemented, {len(names) - len(impl)} trampolines')
